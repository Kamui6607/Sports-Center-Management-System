export const label = (s: string) => labels[s] || s;
export const money = (v: unknown) =>
  v == null || v === "" || !Number.isFinite(Number(v))
    ? "—"
    : new Intl.NumberFormat("vi-VN", {
        style: "currency",
        currency: "VND",
      }).format(Number(v));
export function at(row: unknown, path: string): unknown {
  if (path === "sportsLabel") return sportNames(row);
  if (path === "areaTypesLabel") {
    const areaTypes = row && typeof row === "object"
      ? (row as Record<string, unknown>).areaTypes
      : undefined;
    return Array.isArray(areaTypes)
      ? areaTypes.map((value) => label(String(value))).join(", ")
      : areaTypes;
  }
  return path
    .split(".")
    .reduce<unknown>(
      (v, k) =>
        v && typeof v === "object"
          ? (v as Record<string, unknown>)[k]
          : undefined,
      row,
    );
}
export function display(v: unknown): string {
  if (v == null) return "—";
  if (typeof v === "boolean") return v ? "Hoạt động" : "Ngừng hoạt động";
  if (typeof v === "object")
    return Array.isArray(v)
      ? `${v.length} mục`
      : String(at(v, "name") || at(v, "fullName") || "—");
  if (typeof v === "string" && /^\d{4}-\d{2}-\d{2}T/.test(v))
    return new Date(v).toLocaleString("vi-VN", {
      dateStyle: "short",
      timeStyle: "short",
    });
  return label(String(v));
}
